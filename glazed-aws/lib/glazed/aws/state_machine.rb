require 'json'
require 'google/protobuf'
require 'glazed'
require 'glazed/aws'
require 'glazed/must'
require 'glazed/proto'
require 'glazed/steps'

module Glazed
  module Aws
    # Amazon States Language definition of a Standard state machine running
    # the orchestrated workflows of a config with the {Lambda} function. Each
    # execution checks when nodes are due, waits, runs every workflow's
    # batch of due nodes, and checks again, until another execution waits
    # for the next due node instead. Each step is one state: consecutive
    # per-node steps run in a Map over the batch, batch steps run once.
    #
    # @example
    #   definition = Glazed::Aws::StateMachine.new(config:, function_arn: 'arn:aws:lambda:...:function:glazed').to_h
    class StateMachine
      # Raised when a workflow cannot run under Step Functions.
      class Unsupported < Glazed::Error; end

      # Nodes processed in parallel when neither the caller nor the config sets it.
      DEFAULT_MAX_CONCURRENCY = 4 #: Integer
      # Errors of the Lambda service rather than of the function, worth retrying.
      LAMBDA_ERRORS = [
        'Lambda.ServiceException', 'Lambda.AWSLambdaException', 'Lambda.SdkClientException', 'Lambda.TooManyRequestsException',
      ].freeze #: Array[String]
      # Longest state name Step Functions accepts.
      MAX_STATE_NAME = 80 #: Integer

      #: type state = Hash[String, untyped]

      # @param config [Proto::V1::Config] the config, with orchestrator settings
      # @param function_arn [String] ARN of the {Lambda} function
      # @param max_concurrency [Integer, nil] nodes processed in parallel; the config's jobs when nil
      # @param grace_seconds [Integer, nil] seconds after waking until another execution may take over;
      #   the longest lease when nil
      # @param max_cycles [Integer, nil] cycles after which an execution ends; 20 when nil
      # @raise [Glazed::Error] when the config has no orchestrator settings
      #: (config: Proto::V1::Config, function_arn: String, ?max_concurrency: Integer?, ?grace_seconds: Integer?, ?max_cycles: Integer?) -> void
      def initialize(config:, function_arn:, max_concurrency: nil, grace_seconds: nil, max_cycles: nil)
        @config = config #: Proto::V1::Config
        settings = config.orchestrator or raise Glazed::Error, 'orchestrator is not configured'
        @settings = settings #: Proto::V1::Orchestrator
        @function_arn = function_arn #: String
        jobs = config.jobs.zero? ? DEFAULT_MAX_CONCURRENCY : config.jobs
        @max_concurrency = max_concurrency || jobs #: Integer
        @grace_seconds = grace_seconds #: Integer?
        @max_cycles = max_cycles #: Integer?
      end

      # Storages that work under Step Functions only with care, with why.
      #
      # @return [Array<String>] the warnings
      #: () -> Array[String]
      def warnings
        storages_written.filter_map do |name|
          case Must.because(@config.storages[name]) { 'steps are checked against the storages' }.backend
          when :filesystem then "storage #{name} is a local directory; every Lambda instance has its own"
          when :git
            git = Must.because(@config.storages[name]&.git) { 'backend is git' }
            "storage #{name} is a local git repository without remote; every Lambda instance has its own" if git.remote.empty?
          end
        end
      end

      # @return [Hash] the definition
      # @raise [Unsupported] when a workflow writes to memory storage, which does not outlive one task
      # @raise [Finder::NotFound, PluginRegistry::UnknownPlugin] when a step's implementation is not available
      #: () -> Hash[String, untyped]
      def to_h
        memory = storages_written.select { @config.storages[it]&.backend == :memory }
        raise Unsupported, "memory storages do not outlive a Lambda invocation: #{memory.join(', ')}" unless memory.empty?

        {
          'Comment' => 'glazed coordinator, generated by glazed-aws state-machine',
          'QueryLanguage' => 'JSONata',
          'StartAt' => 'Start',
          'States' => {
            'Start' => {'Type' => 'Pass', 'Assign' => {'cycle' => 0}, 'Next' => 'Check'},
            'Check' => invoke(
              {'check' => {
                'token' => '{% $states.context.Execution.Id %}', 'cycle' => '{% $cycle %}',
                'grace' => "#{@grace_seconds || 0}s", 'max_cycles' => @max_cycles || 0,
              }},
              execution_input: '{% $cycle = 0 ? $states.context.Execution.Input : null %}',
            ).merge('Retry' => [retry_on(LAMBDA_ERRORS + ['States.TaskFailed'])], 'Next' => 'Armed?'),
            'Armed?' => {
              'Type' => 'Choice',
              'Choices' => [{'Condition' => '{% $exists($states.input.wait_until) %}', 'Next' => 'Sleep'}],
              'Default' => 'Done',
            },
            'Sleep' => {'Type' => 'Wait', 'Timestamp' => '{% $states.input.wait_until %}', 'Next' => 'Prepare'},
            'Prepare' => invoke({'prepare' => {}}).merge('Retry' => [retry_on(LAMBDA_ERRORS + ['States.TaskFailed'])], 'Next' => 'Workflows'),
            'Workflows' => {
              'Type' => 'Parallel',
              'Branches' => @settings.workflows.keys.sort.map { branch(it) },
              'Catch' => [{'ErrorEquals' => ['States.ALL'], 'Next' => 'Next cycle'}],
              'Next' => 'Next cycle',
            },
            'Next cycle' => {'Type' => 'Pass', 'Assign' => {'cycle' => '{% $cycle + 1 %}'}, 'Next' => 'Check'},
            'Done' => {'Type' => 'Succeed'},
          },
        }
      end

      # @param workflow [String] workflow name
      # @return [Hash] the Parallel branch running the workflow's batch
      #: (String workflow) -> StateMachine::state
      private def branch(workflow)
        steps = Must.because(@config.workflows[workflow]) { 'validation checks orchestrated workflows exist' }.steps.to_a
        chunks = steps.chunk_while { |a, b| node_step?(a) && node_step?(b) }.to_a
        complete = name(workflow, 'complete')
        states = {} #: Hash[String, StateMachine::state]
        maps = 0
        names = chunks.map { |chunk| node_step?(chunk.fetch(0)) ? name(workflow, "each node ##{maps += 1}") : name(workflow, chunk.fetch(0).name) }
        names << complete

        start = name(workflow, 'batch')
        states[start] = {'Type' => 'Pass', 'Output' => "{% $lookup($states.input.batches, #{JSON.generate(workflow)}) %}", 'Next' => name(workflow, 'any due?')}
        states[name(workflow, 'any due?')] = {
          'Type' => 'Choice',
          'Choices' => [{'Condition' => '{% $count($states.input.nodes) > 0 %}', 'Next' => names.fetch(0)}],
          'Default' => name(workflow, 'none due'),
        }
        states[name(workflow, 'none due')] = {'Type' => 'Succeed'}
        chunks.each_with_index do |chunk, index|
          following = names.fetch(index + 1)
          if node_step?(chunk.fetch(0))
            states[names.fetch(index)] = map(workflow, chunk, names.fetch(index), following)
          else
            step = chunk.fetch(0)
            failed = "{% $merge([$states.input, {\"error\": #{JSON.generate("#{step.name}: ")} & $states.errorOutput.Error & \": \" & $states.errorOutput.Cause}]) %}"
            # A failed batch skips the remaining steps.
            after = following == complete ? complete : name(workflow, "#{step.name} failed?")
            states[names.fetch(index)] = invoke({'batch_step' => {'step' => step.name, 'batch' => '{% $states.input %}'}}).merge(
              'Retry' => [retry_on(LAMBDA_ERRORS)],
              'Catch' => [{'ErrorEquals' => ['States.ALL'], 'Output' => failed, 'Next' => complete}],
              'Next' => after,
            )
            if after != complete
              states[after] = {
                'Type' => 'Choice',
                'Choices' => [{'Condition' => '{% $exists($states.input.error) %}', 'Next' => complete}],
                'Default' => following,
              }
            end
          end
        end
        states[complete] = invoke({'complete' => {'batch' => '{% $states.input %}'}}).merge(
          'Retry' => [retry_on(LAMBDA_ERRORS + ['States.TaskFailed'])],
          'Output' => '{% {"workflow": $states.result.Payload.workflow, "nodes": $count($states.result.Payload.nodes)} %}',
          'End' => true,
        )
        {'StartAt' => start, 'States' => states}
      end

      # @param workflow [String] workflow name
      # @param chunk [Array<Proto::V1::Step>] consecutive per-node steps
      # @param map_name [String] name of the Map state
      # @param following [String] state after the Map
      # @return [Hash] the Map state running the steps for each node of the batch
      #: (String workflow, Array[Proto::V1::Step] chunk, String map_name, String following) -> StateMachine::state
      private def map(workflow, chunk, map_name, following)
        done = name(workflow, "#{map_name.delete_prefix("#{workflow}: ")} done")
        states = {} #: Hash[String, StateMachine::state]
        chunk.each_with_index do |step, index|
          after = chunk[index + 1]&.then { name(workflow, it.name) } || done
          failure = '{% {"state": $states.input.state, "failure": ' \
                    "{\"step\": #{JSON.generate(step.name)}, \"error\": $states.errorOutput.Error & \": \" & $states.errorOutput.Cause}} %}"
          states[name(workflow, step.name)] = invoke(
            {'node_step' => {'workflow' => workflow, 'step' => step.name, 'outcome' => '{% $states.input %}'}},
          ).merge(
            'Retry' => [retry_on(LAMBDA_ERRORS)],
            'Catch' => [{'ErrorEquals' => ['States.ALL'], 'Output' => failure, 'Next' => after}],
            'Next' => after,
          )
        end
        states[done] = {'Type' => 'Pass', 'End' => true}
        {
          'Type' => 'Map',
          'Items' => '{% $states.input.nodes %}',
          'MaxConcurrency' => @max_concurrency,
          'ItemProcessor' => {'ProcessorConfig' => {'Mode' => 'INLINE'}, 'StartAt' => name(workflow, chunk.fetch(0).name), 'States' => states},
          'Output' => '{% $merge([$states.input, {"nodes": $states.result}]) %}',
          'Next' => following,
        }
      end

      # @param task [Hash] the glazed.v1.CoordinatorTask, with JSONata expressions
      # @param execution_input [String, nil] JSONata expression of the execution input to pass
      # @return [Hash] a Task state invoking the function
      #: (Hash[String, untyped] task, ?execution_input: String?) -> StateMachine::state
      private def invoke(task, execution_input: nil)
        payload = {'task' => task} #: Hash[String, untyped]
        payload['execution_input'] = execution_input if execution_input
        {
          'Type' => 'Task',
          'Resource' => 'arn:aws:states:::lambda:invoke',
          'Arguments' => {'FunctionName' => @function_arn, 'Payload' => payload},
          'Output' => '{% $states.result.Payload %}',
        }
      end

      # @param errors [Array<String>] errors to retry
      # @return [Hash] a retrier with backoff
      #: (Array[String] errors) -> Hash[String, untyped]
      private def retry_on(errors)
        {'ErrorEquals' => errors, 'IntervalSeconds' => 2, 'MaxAttempts' => 3, 'BackoffRate' => 2, 'JitterStrategy' => 'FULL'}
      end

      # @param workflow [String] workflow name
      # @param label [String] what the state does
      # @return [String] a state name unique across the state machine
      # @raise [Unsupported] when the name exceeds what Step Functions accepts
      #: (String workflow, String label) -> String
      private def name(workflow, label)
        name = "#{workflow}: #{label}"
        raise Unsupported, "state name #{name.inspect} is longer than #{MAX_STATE_NAME} characters" if name.length > MAX_STATE_NAME

        name
      end

      # @param step [Proto::V1::Step] step definition
      # @return [Boolean] whether the step runs for each node
      #: (Proto::V1::Step step) -> bool
      private def node_step?(step)
        implementation = if (packed = step.plugin)
          Steps::PLUGINS.resolve(packed).first
        else
          Steps.find(Must.because(step.action) { 'validation requires an action' })
        end
        implementation.is_a?(Class) && implementation.ancestors.include?(Steps::NodeStep)
      end

      # @return [Array<String>] names of the storages steps of the orchestrated workflows write to
      #: () -> Array[String]
      private def storages_written
        @settings.workflows.keys.flat_map do |workflow|
          (@config.workflows[workflow]&.steps || []).filter_map do |step|
            action = step.action
            next unless action && action != :plugin

            field = Proto::V1::Step.descriptor.lookup(action.to_s)&.subtype&.lookup('storage')
            next unless field

            storage = field.get(step[action.to_s]) #: untyped
            storage.is_a?(String) && !storage.empty? ? storage : nil
          end
        end.uniq
      end
    end
  end
end
